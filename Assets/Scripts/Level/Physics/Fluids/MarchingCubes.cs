    // Pre-allocated buffers reused for speed
    private Dictionary<long, int> vertexCache;

    public void Init(int res)
    {
        resolution = Mathf.Max(8, res);
        vertexCache = new Dictionary<long, int>(resolution * resolution * resolution);
    }

    // Public Generate API
    // field: float[res+1, res+1, res+1]
    // iso: threshold
    // origin: world min
    // step: spacing vector
    public void Generate(float[,,] field, float iso, Vector3 origin, Vector3 step, out List<Vector3> vertices, out List<int> triangles, out List<Vector3> normals)
    {
        vertices = new List<Vector3>();
        triangles = new List<int>();
        normals = new List<Vector3>();
        vertexCache.Clear();

        int nx = field.GetLength(0) - 1;
        int ny = field.GetLength(1) - 1;
        int nz = field.GetLength(2) - 1;

        // Iterate cells
        for (int z = 0; z < nz; z++)
        {
            for (int y = 0; y < ny; y++)
            {
                for (int x = 0; x < nx; x++)
                {
                    // Corners values and positions
                    float[] val = new float[8];
                    Vector3[] pos = new Vector3[8];

                    for (int i = 0; i < 8; i++)
                    {
                        int ix = x + VertexOffset[i, 0];
                        int iy = y + VertexOffset[i, 1];
                        int iz = z + VertexOffset[i, 2];
                        val[i] = field[ix, iy, iz];
                        pos[i] = origin + new Vector3(ix * step.x, iy * step.y, iz * step.z);
                    }

                    // Determine cube index
                    int cubeIndex = 0;
                    for (int i = 0; i < 8; i++) if (val[i] > iso) cubeIndex |= 1 << i;
                    int edges = edgeTable[cubeIndex];
                    if (edges == 0) continue;

                    // Compute edge vertices
                    Vector3[] edgeVertex = new Vector3[12];
                    for (int e = 0; e < 12; e++)
                    {
                        if ((edges & (1 << e)) != 0)
                        {
                            int a = EdgeConnection[e, 0];
                            int b = EdgeConnection[e, 1];
                            float t = (iso - val[a]) / (val[b] - val[a] + 1e-9f);
                            t = Mathf.Clamp01(t);
                            edgeVertex[e] = Vector3.Lerp(pos[a], pos[b], t);
                        }
                    }

                    // Create triangles
                    for (int ti = 0; ti < 16; ti += 3)
                    {
                        int a = triTable[cubeIndex, ti];
                        if (a < 0) break;
                        int b = triTable[cubeIndex, ti + 1];
                        int c = triTable[cubeIndex, ti + 2];

                        int ia = GetVertexIndex(edgeVertex[a], vertices, vertexCache);
                        int ib = GetVertexIndex(edgeVertex[b], vertices, vertexCache);
                        int ic = GetVertexIndex(edgeVertex[c], vertices, vertexCache);

                        triangles.Add(ia);
                        triangles.Add(ib);
                        triangles.Add(ic);
                    }
                }
            }
        }

        // compute normals
        normals = new List<Vector3>(new Vector3[vertices.Count]);
        for (int i = 0; i < triangles.Count; i += 3)
        {
            int i0 = triangles[i], i1 = triangles[i + 1], i2 = triangles[i + 2];
            Vector3 v0 = vertices[i0], v1 = vertices[i1], v2 = vertices[i2];
            Vector3 n = Vector3.Cross(v1 - v0, v2 - v0);
            if (n.sqrMagnitude > 0.0f)
            {
                n.Normalize();
                normals[i0] += n;
                normals[i1] += n;
                normals[i2] += n;
            }
        }

        for (int i = 0; i < normals.Count; i++)
        {
            normals[i] = normals[i].normalized;
        }
    }

    private int GetVertexIndex(Vector3 v, List<Vector3> verts, Dictionary<long, int> cache)
    {
        long key = HashPosition(v);
        if (cache.TryGetValue(key, out int idx)) return idx;
        idx = verts.Count;
        verts.Add(v);
        cache[key] = idx;
        return idx;
    }

    private long HashPosition(Vector3 v)
    {
        // Hash coordinates with limited precision to reduce duplicates
        int x = Mathf.RoundToInt(v.x * 1000f);
        int y = Mathf.RoundToInt(v.y * 1000f);
        int z = Mathf.RoundToInt(v.z * 1000f);
        return (((long)x & 0xffffffff) << 32) | ((uint)y << 16) | (uint)z;
    }

